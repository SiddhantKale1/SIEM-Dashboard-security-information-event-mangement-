import secrets
import string
import uuid
from datetime import datetime, timedelta, timezone
from fastapi import APIRouter, Depends, HTTPException, status
import logging

from app.database.connection import get_db
from app.auth.security import get_password_hash, verify_password, create_access_token
from app.schemas.enrollment import DeviceRegistrationRequest, DeviceRegistrationResponse, EnrollmentTokenResponse
from app.api.auth import get_current_user

router = APIRouter(prefix="/api/v1/enrollment", tags=["enrollment"])
logger = logging.getLogger(__name__)

def generate_enrollment_token() -> str:
    # Generates a format like ENROLL-XXXX-XXXX
    part1 = ''.join(secrets.choice(string.ascii_uppercase + string.digits) for _ in range(4))
    part2 = ''.join(secrets.choice(string.ascii_uppercase + string.digits) for _ in range(4))
    return f"ENROLL-{part1}-{part2}"

@router.post("/token", response_model=EnrollmentTokenResponse)
async def create_enrollment_token(current_user: dict = Depends(get_current_user)):
    db = get_db()
    token = generate_enrollment_token()
    token_hash = get_password_hash(token)
    expires_at = datetime.now(timezone.utc) + timedelta(hours=1)
    
    await db.enrollment_tokens.insert_one({
        "token_hash": token_hash,
        "created_by": current_user["username"],
        "created_at": datetime.now(timezone.utc),
        "expires_at": expires_at,
        "used": False,
        "device_id": None
    })
    
    logger.info(f"Enrollment token generated by {current_user['username']}")
    return {"token": token, "expires_at": expires_at}

@router.post("/register", response_model=DeviceRegistrationResponse)
async def register_device(request: DeviceRegistrationRequest):
    db = get_db()
    
    # In a real scenario, finding the token by verifying hashes is inefficient if we just iterate.
    # To optimize, we should store a token ID prefix in plaintext and hash the rest, but for MVP
    # we can do a simpler approach: the token itself acts as a secret. 
    # Since MVP is just a proof of concept, we can look up unexpired, unused tokens and verify.
    # Wait, PyMongo doesn't easily support querying by verified hash without iterating. 
    # Let's just find all unused, unexpired tokens and verify them.
    # Alternatively, use a faster lookup by splitting the token: id + secret.
    
    # Better approach for MVP without changing token format:
    # Just iterate through unused, unexpired tokens. (Fine for small MVP scale).
    cursor = db.enrollment_tokens.find({
        "used": False,
        "expires_at": {"$gt": datetime.now(timezone.utc)}
    })
    
    valid_token_doc = None
    async for doc in cursor:
        if verify_password(request.token, doc["token_hash"]):
            valid_token_doc = doc
            break
            
    if not valid_token_doc:
        logger.warning(f"Failed enrollment attempt from {request.ip_address} - Invalid or expired token")
        raise HTTPException(status_code=400, detail="Invalid or expired enrollment token")

    # Token is valid, register device
    device_id = f"device-{uuid.uuid4().hex[:8]}"
    
    new_device = {
        "device_id": device_id,
        "hostname": request.hostname,
        "ip_address": request.ip_address,
        "mac_address": request.mac_address,
        "os": request.os,
        "os_version": request.os_version,
        "agent_version": request.agent_version,
        "status": "online",
        "last_seen": datetime.now(timezone.utc),
        "enrolled_at": datetime.now(timezone.utc),
        "created_at": datetime.now(timezone.utc)
    }
    
    await db.devices.insert_one(new_device)
    
    # Mark token as used
    await db.enrollment_tokens.update_one(
        {"_id": valid_token_doc["_id"]},
        {"$set": {"used": True, "device_id": device_id}}
    )
    
    # Add audit event
    await db.device_events.insert_one({
        "device_id": device_id,
        "event": "enrolled",
        "timestamp": datetime.now(timezone.utc),
        "details": f"Enrolled via token created by {valid_token_doc['created_by']}"
    })
    
    # Generate long-lived device credential (10 years)
    # Alternatively we can just issue a JWT with device_id
    device_credential = create_access_token(
        data={"sub": device_id, "role": "device"},
        expires_delta=timedelta(days=3650)
    )
    
    logger.info(f"Device {device_id} ({request.hostname}) enrolled successfully")
    return {"device_id": device_id, "device_credential": device_credential}
