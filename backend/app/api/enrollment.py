def generate_enrollment_token() -> str:
    part1 = ''.join(secrets.choice(string.ascii_uppercase + string.digits) for _ in range(4))
    part2 = ''.join(secrets.choice(string.ascii_uppercase + string.digits) for _ in range(4))
    return f"ENROLL-{part1}-{part2}"

def hash_enrollment_token(token: str) -> str:
    return hashlib.sha256(token.strip().encode("utf-8")).hexdigest()

@router.post("/token")
async def create_enrollment_token(
    reusable: bool = Query(True, description="Allow token to be used on multiple endpoint PCs"),
    days_valid: int = Query(30, ge=1, le=365),
    current_user: dict = Depends(get_current_user)
):
    db = get_db()
    token = generate_enrollment_token()
    token_hash = hash_enrollment_token(token)
    expires_at = datetime.now(timezone.utc) + timedelta(days=days_valid)
    net_info = NetworkManager.get_local_network_info()
    server_ip = net_info.get("server_ip", "127.0.0.1")
    server_url = f"http://{server_ip}:8000"

    await db.enrollment_tokens.insert_one({
        "token_hash": token_hash,
        "token_preview": f"{token[:11]}...",
        "created_by": current_user["username"],
        "created_at": datetime.now(timezone.utc),
        "expires_at": expires_at,
        "reusable": reusable,
        "used": False,
        "use_count": 0,
        "device_ids": []
    })
    
    logger.info(f"Enrollment token generated by {current_user['username']} (reusable={reusable})")

    # Generate ready-to-run one-line boot-persistent installer commands
    linux_cmd = f"curl -sSL \"{server_url}/api/v1/enrollment/install.sh\" | sudo bash -s -- --server \"{server_url}\" --token \"{token}\""
    windows_cmd = f"powershell -ExecutionPolicy Bypass -Command \"irm '{server_url}/api/v1/enrollment/install.ps1?token={token}&server={server_url}' | iex\""

    return {
        "token": token,
        "expires_at": expires_at.isoformat(),
        "reusable": reusable,
        "server_url": server_url,
        "install_commands": {
            "linux": linux_cmd,
            "windows": windows_cmd
        }
    }

@router.post("/register", response_model=DeviceRegistrationResponse)
async def register_device(request: DeviceRegistrationRequest):
    db = get_db()
    now = datetime.now(timezone.utc)
    token_str = (request.token or "").strip()
    sha_hash = hash_enrollment_token(token_str)
    
    # 1. Fast direct O(1) hash lookup (<1ms)
    valid_token_doc = await db.enrollment_tokens.find_one({"token_hash": sha_hash})
    if valid_token_doc:
        exp = valid_token_doc.get("expires_at")
        if exp:
            if isinstance(exp, str):
                try:
                    exp = datetime.fromisoformat(exp.replace("Z", "+00:00"))
                except Exception:
                    pass
            if hasattr(exp, "tzinfo") and exp.tzinfo is None:
                exp = exp.replace(tzinfo=timezone.utc)
            if hasattr(exp, "timestamp") and exp < now:
                valid_token_doc = None
        if valid_token_doc and not valid_token_doc.get("reusable", False) and valid_token_doc.get("used", False):
            valid_token_doc = None

    # 2. Backward compatibility fallback for legacy bcrypt tokens (checked newest first!)
    if not valid_token_doc:
        cursor = db.enrollment_tokens.find({}).sort("created_at", -1)
        async for doc in cursor:
            exp = doc.get("expires_at")
            if exp:
                if isinstance(exp, str):
                    try:
                        exp = datetime.fromisoformat(exp.replace("Z", "+00:00"))
                    except Exception:
                        pass
                if hasattr(exp, "tzinfo") and exp.tzinfo is None:
                    exp = exp.replace(tzinfo=timezone.utc)
                if hasattr(exp, "timestamp") and exp < now:
                    continue

            if not doc.get("reusable", False) and doc.get("used", False):
                continue

            th = doc.get("token_hash", "")
            if th and th.startswith("$2"):
                # Run bcrypt in worker thread so event loop never freezes
                is_match = await asyncio.to_thread(verify_password, token_str, th)
                if is_match:
                    valid_token_doc = doc
                    # Automatically upgrade stored hash to instant SHA-256 for all future checks
                    await db.enrollment_tokens.update_one(
                        {"_id": doc["_id"]},
                        {"$set": {"token_hash": sha_hash, "token_preview": f"{token_str[:11]}..."}}
                    )
                    break
            
    if not valid_token_doc:
        logger.warning(f"Failed enrollment attempt from {request.ip_address} - Invalid or expired token")
        raise HTTPException(status_code=400, detail="Invalid or expired enrollment token")

    # Generate or reuse permanent device ID (avoiding duplicate records for same MAC)
    existing_device = None
    if request.mac_address:
        existing_device = await db.devices.find_one({"mac_address": request.mac_address})

    device_id = (existing_device.get("device_id") if existing_device and existing_device.get("device_id") else None) or f"device-{uuid.uuid4().hex[:8]}"
    net_info = NetworkManager.get_local_network_info()
    
    new_device = {
        "device_id": device_id,
        "hostname": request.hostname,
        "ip_address": request.ip_address,
        "mac_address": request.mac_address,
        "os": request.os,
        "os_version": request.os_version,
        "agent_version": request.agent_version,
        "status": "online",
        "subnet": net_info.get("subnet", "192.168.1.0/24"),
        "last_seen": now,
        "enrolled_at": existing_device.get("enrolled_at", now) if existing_device else now,
        "created_at": existing_device.get("created_at", now) if existing_device else now
    }
    
    if existing_device:
        await db.devices.update_one({"_id": existing_device["_id"]}, {"$set": new_device})
    else:
        await db.devices.insert_one(new_device)
    
    # Update token usage
    update_fields = {
        "used": True if not valid_token_doc.get("reusable", False) else False
    }
    await db.enrollment_tokens.update_one(
        {"_id": valid_token_doc["_id"]},
        {
            "$set": update_fields,
            "$inc": {"use_count": 1},
            "$push": {"device_ids": device_id}
        }
    )
    
    # Audit log
    await db.device_events.insert_one({
        "device_id": device_id,
        "event": "enrolled",
        "timestamp": now,
        "details": f"Enrolled via token created by {valid_token_doc['created_by']}"
    })
    
    # Record initial connection history session
    await NetworkManager.record_connection_event(
        db=db,
        device_id=device_id,
        hostname=request.hostname,
        ip=request.ip_address,
        mac=request.mac_address,
        os_name=request.os,
        event_type="connected"
    )

    # Issue 10-year permanent device credential
    device_credential = create_access_token(
        data={"sub": device_id, "role": "device"},
        expires_delta=timedelta(days=3650)
    )
    
    logger.info(f"Permanent device {device_id} ({request.hostname}) enrolled successfully")
    return {"device_id": device_id, "device_credential": device_credential}

@router.get("/tokens")
async def list_tokens(current_user: dict = Depends(get_current_user)):
    """List all active enrollment tokens."""
    db = get_db()
    now = datetime.now(timezone.utc)
    cursor = db.enrollment_tokens.find({}).sort("created_at", -1)
    tokens = await cursor.to_list(length=100)
    result = []
    for t in tokens:
        exp = t.get("expires_at")
        if exp:
            if isinstance(exp, str):
                try:
                    exp = datetime.fromisoformat(exp.replace("Z", "+00:00"))
                except Exception:
                    pass
            if hasattr(exp, "tzinfo") and exp.tzinfo is None:
                exp = exp.replace(tzinfo=timezone.utc)
            if hasattr(exp, "timestamp") and exp < now:
                continue

        result.append({
            "id": str(t["_id"]),
            "token_preview": t.get("token_preview", "ENROLL-****"),
            "created_by": t.get("created_by", "admin"),
            "reusable": t.get("reusable", False),
            "use_count": t.get("use_count", 1 if t.get("used") else 0),
            "created_at": t["created_at"].isoformat() if hasattr(t.get("created_at"), "isoformat") else str(t.get("created_at")),
            "expires_at": t["expires_at"].isoformat() if hasattr(t.get("expires_at"), "isoformat") else str(t.get("expires_at")),
        })
    return result

@router.delete("/tokens/{token_id}")
async def revoke_token(token_id: str, current_user: dict = Depends(get_current_user)):
    """Revoke an enrollment token."""
    db = get_db()
    tokens_cursor = db.enrollment_tokens.find({})
    tokens = await tokens_cursor.to_list(length=200)
    target = next((t for t in tokens if str(t["_id"]) == token_id), None)
    if not target:
        raise HTTPException(status_code=404, detail="Token not found")
    
    await db.enrollment_tokens.update_one(
        {"_id": target["_id"]},
        {"$set": {"expires_at": datetime.now(timezone.utc) - timedelta(seconds=1), "used": True}}
    )
    return {"detail": "Token revoked"}

@router.api_route("/install.sh", methods=["GET", "HEAD"])
async def serve_linux_installer(request: Request):
    """
    Dynamically generates and serves the permanent Linux systemd agent installer.
    Installs `/etc/systemd/system/siem-agent.service` so it persists across every boot!
    """
    net_info = NetworkManager.get_local_network_info()
    token = request.query_params.get("token") or ""
    server = request.query_params.get("server") or ""
    srv = server or f"http://{net_info.get('server_ip', '127.0.0.1')}:8000"
    tok = token or ""

    script = f'''#!/usr/bin/env bash
set -e

# ====================================================================
# SIEM Real-Time Endpoint Agent — Boot-Persistent Installer (Linux)
# ====================================================================

echo "[*] Initializing SIEM Agent Installation..."

SERVER_URL="{srv}"
ENROLLMENT_TOKEN="{tok}"

# Check arguments
while [[ "$#" -gt 0 ]]; do
    case $1 in
        --server) SERVER_URL="$2"; shift ;;
        --token) ENROLLMENT_TOKEN="$2"; shift ;;
    esac
    shift
done

if [ -z "$ENROLLMENT_TOKEN" ]; then
    echo "[-] Error: ENROLLMENT_TOKEN is required. Pass --token <TOKEN>"
    exit 1
fi

echo "[*] Target SIEM Server: $SERVER_URL"

# Install dependencies if missing
if ! command -v python3 &> /dev/null; then
    echo "[*] Installing Python 3..."
    if command -v apt-get &> /dev/null; then
        apt-get update -qq && apt-get install -y -qq python3 python3-pip python3-psutil
    elif command -v dnf &> /dev/null; then
        dnf install -y -q python3 python3-pip python3-psutil
    fi
fi

# Ensure psutil is installed (fallback to native if pip fails)
python3 -c "import psutil" 2>/dev/null || pip3 install psutil 2>/dev/null || true

# Prepare directories
AGENT_DIR="/opt/siem-agent"
CONFIG_DIR="/etc/siem-agent"
mkdir -p "$AGENT_DIR" "$CONFIG_DIR"
chmod 700 "$CONFIG_DIR"

# Download the universal agent code
echo "[*] Downloading SIEM Universal Agent..."
curl -sSL "$SERVER_URL/api/v1/enrollment/agent.py" -o "$AGENT_DIR/siem_agent.py"
chmod 755 "$AGENT_DIR/siem_agent.py"

# Write initial bootstrapping config
cat <<EOF > "$CONFIG_DIR/agent_config.json"
{{
    "server_url": "$SERVER_URL",
    "enrollment_token": "$ENROLLMENT_TOKEN"
}}
EOF
chmod 600 "$CONFIG_DIR/agent_config.json"

# Create boot-persistent systemd unit
echo "[*] Registering systemd background service (siem-agent.service)..."
cat <<EOF > /etc/systemd/system/siem-agent.service
[Unit]
Description=SIEM AI-Driven Real-Time Security Monitoring Agent
After=network.target network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/bin/python3 $AGENT_DIR/siem_agent.py
Restart=always
RestartSec=10
WorkingDirectory=$AGENT_DIR
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable siem-agent.service
systemctl restart siem-agent.service

echo "[+] SUCCESS: SIEM Agent is permanently installed and active!"
echo "[+] Service will automatically start on every system boot."
echo "[+] Verify status with: systemctl status siem-agent"
'''
    return Response(content=script, media_type="text/x-shellscript")

@router.api_route("/install.ps1", methods=["GET", "HEAD"])
async def serve_windows_installer(request: Request):
    """
    Dynamically generates and serves the permanent Windows boot agent installer.
    Creates a persistent Scheduled Task that runs headless at boot with Highest Privileges!
    """
    net_info = NetworkManager.get_local_network_info()
    token = request.query_params.get("token") or ""
    server = request.query_params.get("server") or ""
    srv = server or f"http://{net_info.get('server_ip', '127.0.0.1')}:8000"
    tok = token or ""

    script = f'''# ====================================================================
# SIEM Real-Time Endpoint Agent — Boot-Persistent Installer (Windows)
# ====================================================================

$ServerUrl = "{srv}"
$Token = "{tok}"

Write-Host "[*] Initializing SIEM Windows Permanent Agent Installer..." -ForegroundColor Cyan

# Test python availability
$PythonCmd = (Get-Command python, py, python3 -ErrorAction SilentlyContinue | Select-Object -First 1).Source
if (-not $PythonCmd) {{
    Write-Host "[!] Warning: Python executable not found in PATH. Please ensure Python 3 is installed." -ForegroundColor Yellow
    $PythonCmd = "python"
}} else {{
    Write-Host "[*] Found Python: $PythonCmd" -ForegroundColor Green
    & $PythonCmd -m pip install psutil -q 2>$null
}}

$InstallDir = "$env:ProgramData\\SIEMAgent"
if (!(Test-Path $InstallDir)) {{
    New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
}}

# Write initial config
$Config = @{{
    server_url = $ServerUrl
    enrollment_token = $Token
}} | ConvertTo-Json
$Config | Set-Content -Path "$InstallDir\\agent_config.json"

# Download universal agent
Write-Host "[*] Fetching SIEM Agent code from $ServerUrl..." -ForegroundColor Cyan
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
Invoke-WebRequest -Uri "$ServerUrl/api/v1/enrollment/agent.py" -OutFile "$InstallDir\\siem_agent.py" -UseBasicParsing

# Create launcher vbs script for silent headless execution (no window popups)
$VbsLauncher = @"
Set WshShell = CreateObject("WScript.Shell")
WshShell.Run """$PythonCmd"" ""$InstallDir\\siem_agent.py""", 0, False
"@
$VbsLauncher | Set-Content -Path "$InstallDir\\run_hidden.vbs"

# Install Windows Task Scheduler job running AtStartup with Highest Privileges
Write-Host "[*] Registering persistent Windows Boot Task 'SIEM-Agent-Persistent'..." -ForegroundColor Cyan
try {{
    $Action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "`"$InstallDir\\run_hidden.vbs`""
    $Trigger = New-ScheduledTaskTrigger -AtStartup
    $Principal = New-ScheduledTaskPrincipal -UserId "SYSTEM" -LogonType ServiceAccount -RunLevel Highest
    $Settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)

    Unregister-ScheduledTask -TaskName "SIEM-Agent-Persistent" -Confirm:$false -ErrorAction SilentlyContinue
    Register-ScheduledTask -TaskName "SIEM-Agent-Persistent" -Action $Action -Trigger $Trigger -Principal $Principal -Settings $Settings -ErrorAction Stop | Out-Null
    Start-ScheduledTask -TaskName "SIEM-Agent-Persistent"
    Write-Host "[+] SUCCESS: Scheduled Task 'SIEM-Agent-Persistent' created and started!" -ForegroundColor Green
}} catch {{
    Write-Host "[*] Running as background process directly..." -ForegroundColor Cyan
    Start-Process wscript.exe -ArgumentList "`"$InstallDir\\run_hidden.vbs`""
}}

Write-Host "[+] SUCCESS: SIEM Windows Agent is permanently installed!" -ForegroundColor Green
Write-Host "[+] It is running headless in the background and will start on every system boot." -ForegroundColor Green
Write-Host "[+] You may safely close this PowerShell window." -ForegroundColor Green
'''
    return Response(content=script, media_type="text/plain")

